#!/usr/bin/env python3
"""Canonical C# formatting: CSharpier, then Roslyn whitespace; checks never edit sources."""
import argparse
from pathlib import Path
import shutil
import stat
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def source_files(root):
    git_root = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=root, capture_output=True, text=True)
    if git_root.returncode == 0 and Path(git_root.stdout.strip()).resolve() == root.resolve():
        result = subprocess.run(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "*.cs"], cwd=root, check=True, capture_output=True)
        names = set(result.stdout.decode().split("\0")) - {""}
    else:
        names = {str(p.relative_to(root)) for p in root.rglob("*.cs") if not {".yard", ".temp", "node_modules", "bin", "obj", ".git"}.intersection(p.relative_to(root).parts)}
    files = []
    for name in names:
        path = root / name
        if not path.is_file() or path.is_symlink() or {"temp", "bin", "obj"}.intersection(Path(name).parts):
            continue
        if path.name.endswith((".Designer.cs", "ModelSnapshot.cs", ".g.cs", ".g.i.cs", ".generated.cs")):
            continue
        header = path.read_bytes()[:2048].lower()
        if b"<auto-generated" in header or b"<autogenerated" in header:
            continue
        files.append(path)
    return sorted(files)


def pipeline(directory):
    subprocess.run(
        ["dotnet", "csharpier", "format", str(directory), "--no-cache", "--log-level", "Warning"],
        cwd=ROOT, check=True,
    )
    subprocess.run(
        ["dotnet", "format", "whitespace", str(directory), "--folder", "--verbosity", "quiet"],
        cwd=ROOT, check=True,
    )


def format_sources(root, files, check=False):
    originals = {path: path.read_bytes() for path in files}
    with tempfile.TemporaryDirectory(prefix="yard-csharp-format-") as temporary:
        sandbox = Path(temporary)
        # Preserve effective configuration without copying project files, credentials or build output.
        configs = {root / ".editorconfig"}
        for source in files:
            configs.update(parent / ".editorconfig" for parent in source.relative_to(root).parents
                           if parent != Path("."))
        for config in configs:
            config = config if config.is_absolute() else root / config
            if config.is_file():
                target = sandbox / config.relative_to(root)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(config, target)
        for path, content in originals.items():
            target = sandbox / path.relative_to(root)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        if files:
            pipeline(sandbox)
        changes = {path: (sandbox / path.relative_to(root)).read_bytes() for path in files
                   if (sandbox / path.relative_to(root)).read_bytes() != originals[path]}
        if check:
            for path in changes:
                print(path.relative_to(root))
            if changes:
                print("Run yard fmt to format these C# files.", file=sys.stderr)
            return 1 if changes else 0
        if any(path.read_bytes() != original for path, original in originals.items()):
            raise RuntimeError("A source changed during formatting; retry after saving your edits.")
        for path, content in changes.items():
            with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".format-", delete=False) as output:
                pending = Path(output.name)
                try:
                    output.write(content)
                    output.flush()
                except BaseException:
                    pending.unlink(missing_ok=True)
                    raise
            try:
                pending.chmod(stat.S_IMODE(path.stat().st_mode))
                pending.replace(path)
            finally:
                pending.unlink(missing_ok=True)
        print(f"Formatted {len(changes)} of {len(files)} C# files.")
        return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--file", type=Path)
    args = parser.parse_args()
    files = source_files(ROOT)
    if args.file:
        selected = (ROOT / args.file).resolve()
        if selected not in files:
            parser.error("--file must select a non-generated, non-ignored C# source in this repository")
        files = [selected]
    try:
        return format_sources(ROOT, files, args.check)
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"C# formatting failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
