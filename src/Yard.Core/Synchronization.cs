using System.Text.Json;
using System.Xml.Linq;

namespace Yard;

public static class Synchronization {
    public static Dictionary<string, string> Expected(Workspace w) {
        var definition = w.Definition;
        var solution = new XElement("Solution");
        foreach (var app in definition.Backends) {
            solution.Add(
                new XElement(
                    "Project",
                    new XAttribute(
                        "Path",
                        Path.GetRelativePath(w.Root, w.Project(app)).Replace('\\', '/')
                    )
                )
            );
            var test =
                $"apps/{app}/tests/{w.ProjectName(app)}.Tests/{w.ProjectName(app)}.Tests.csproj";
            if (File.Exists(Path.Combine(w.Root, test)))
                solution.Add(new XElement("Project", new XAttribute("Path", test)));
        }
        var tools = new {
            version = 1,
            isRoot = true,
            tools = new Dictionary<string, object> {
                ["iugam.yard.cli"] = new { version = Versions.Yard, commands = new[] { "yard" } },
                ["dotnet-ef"] = new { version = Versions.Ef, commands = new[] { "dotnet-ef" } },
                ["csharpier"] = new { version = "1.3.0", commands = new[] { "csharpier" } },
            },
        };
        var result = new Dictionary<string, string> {
            [definition.Name + ".slnx"] = solution + "\n",
            ["pnpm-workspace.yaml"] = "packages:\n  - apps/*\n  - packages/*\n",
            ["packages/ui/src/sources.css"] =
                "/* Generated by yard sync. */\n@source './';\n@source '../../platform/src/';\n"
                + string.Concat(
                    definition.Frontends.Select(name => $"@source '../../../apps/{name}/src/';\n")
                ),
            [".config/dotnet-tools.json"] = JsonSerializer.Serialize(tools, Workspace.Json) + "\n",
        };
        var assembly = typeof(Synchronization).Assembly;
        foreach (
            var name in assembly
                .GetManifestResourceNames()
                .Where(x => x.StartsWith("Yard.Managed/"))
        ) {
            using var reader = new StreamReader(assembly.GetManifestResourceStream(name)!);
            result[name["Yard.Managed/".Length..]] = reader.ReadToEnd();
        }
        foreach (var frontend in definition.Frontends)
            result[$"apps/{frontend}/vite.config.ts"] =
                frontend == "web"
                    ? ViteConfig
                    : ViteConfig.Replace(
                        "base: process.env.YARD_BASE_PATH ?? '/'",
                        $"base: process.env.YARD_BASE_PATH ?? '/{frontend}/'"
                    );
        return result;
    }

    public const string ViteConfig =
        "import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\nimport tailwind from '@tailwindcss/vite';\nexport default defineConfig({\n  plugins: [react(), tailwind()],\n  base: process.env.YARD_BASE_PATH ?? '/',\n  server: {\n    host: '127.0.0.1',\n    port: Number(process.env.PORT ?? 5173),\n    strictPort: true,\n    watch: { usePolling: true, interval: 250 },\n    hmr: { clientPort: Number(process.env.YARD_GATEWAY_PORT ?? 8080) },\n  },\n});\n";

    public static string[] Apply(Workspace w, bool check) {
        var changes = Expected(w)
            .Where(x =>
                !File.Exists(Path.Combine(w.Root, x.Key))
                || File.ReadAllText(Path.Combine(w.Root, x.Key)) != x.Value
            )
            .ToArray();
        if (!check)
            foreach (var (name, content) in changes) {
                var p = Path.Combine(w.Root, name);
                Directory.CreateDirectory(Path.GetDirectoryName(p)!);
                File.WriteAllText(p, content);
            }
        return changes.Select(x => x.Key).ToArray();
    }
}
